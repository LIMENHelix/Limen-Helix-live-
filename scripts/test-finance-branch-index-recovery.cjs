const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('assets/js/finance-clarity-operator.js', 'utf8');
const slice = source.slice(source.indexOf('  var _branchIndex = null;'), source.indexOf('  function _handleLoadBranch('));
const container = { innerHTML: '', classList: { contains: () => false, add() {}, remove() {} } };
let calls = 0;
let response = () => ({ ok: false, status: 404 });
const context = vm.createContext({ Promise, Array, Error, fetch: async () => { calls++; return response(); }, document: { getElementById: () => container }, esc: s => String(s).replaceAll('<', '&lt;') });
vm.runInContext(slice, context);
const flush = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  context._handleDrillClick('drill', 'node', ''); await flush();
  assert.match(container.innerHTML, /finance-branch-index\.json/);
  assert.match(container.innerHTML, /HTTP 404/);
  assert.doesNotMatch(container.innerHTML, /No closely related/);
  response = () => ({ ok: true, json: async () => ({ branches: [] }) });
  context._handleDrillClick('drill', 'node', ''); await flush();
  assert.equal(calls, 2, 'Opening after a failure must retry');
  assert.match(container.innerHTML, /No closely related branches/);
  await context._loadBranchIndex(); assert.equal(calls, 2, 'Valid indexes remain cached');
  vm.runInContext('_branchIndex = null', context);
  response = () => ({ ok: true, json: async () => ({ branches: {} }) });
  context._handleDrillClick('drill', 'node', ''); await flush();
  assert.match(container.innerHTML, /invalid branch index/);
  response = () => { throw new Error('<unsafe>'); };
  context._handleDrillClick('drill', 'node', ''); await flush();
  assert.match(container.innerHTML, /&lt;unsafe>/);
  assert.doesNotMatch(container.innerHTML, /<unsafe>/);
  console.log('PASS Finance branch index: 404 evidence, retry, empty success, cache, malformed data, escaped network error');
})().catch(error => { console.error(error); process.exitCode = 1; });
