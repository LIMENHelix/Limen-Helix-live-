'use strict';
var assert = require('node:assert/strict');
var Trace = require('../lib/product-domain-business-trace-readout.js');
var Learning = require('../lib/autofire-learning.js');
var Efference = require('../lib/autofire-efference.js');
module.exports = async function (store, product, owner, copy, at) {
  var empty = new store.constructor();
  assert.equal((await Trace.read(empty, product, at)).status, 'UNOBSERVED');
  var readonly = Object.create(store);
  ['set', 'setIfAbsent', 'lpush', 'ltrim', 'del'].forEach(function (name) { readonly[name] = async function () { throw new Error('readout must not write'); }; });
  var row = await Trace.read(readonly, product, at);
  assert.equal(row.status, 'RECORDED', row.reason);
  assert.equal(row.ownerDomain, owner);
  assert.equal(row.command.id, copy.id);
  assert.equal(row.command.receipt.kind, 'PERSISTENCE-RECEIPT');
  assert.equal(row.command.artifactGenerationOnly, true);
  assert.equal(row.externalActionAuthorized, false);
  assert.match(row.reason, /independent evaluation and revenue remain separate/);
  var key = Efference.recordKey(copy.id), original = await store.get(key);
  store.values[key] = Object.assign({}, original, { emittedAt: at + 1 });
  assert.equal((await Trace.read(readonly, product, at)).status, 'UNAVAILABLE');
  store.values[key] = Object.assign({}, original, { receipt: Object.assign({}, original.receipt, { applied: false }) });
  assert.equal((await Trace.read(readonly, product, at)).reason, 'artifact-persistence-receipt-invalid');
  store.values[key] = original;
  store.values[key] = Object.assign({}, original, { status: 'COMMANDED', resolvedAt: null, receipt: null });
  var pending = await Trace.read(readonly, product, at);
  assert.equal(pending.status, 'RECORDED');
  assert.equal(pending.command.status, 'COMMANDED');
  assert.equal(pending.command.receipt, null, 'a pending command cannot acquire a persistence receipt');
  store.values[key] = Object.assign({}, original, { subjectId: 'another-owner-subject' });
  assert.equal((await Trace.read(readonly, product, at)).reason, 'artifact-command-decision-link-invalid');
  store.values[key] = original;
  var causeKey = Learning.causeKey(copy.actionId), cause = await store.get(causeKey);
  delete store.values[causeKey];
  assert.equal((await Trace.read(readonly, product, at)).reason, 'artifact-command-cause-invalid');
  store.values[causeKey] = cause;
  var selectionKey = 'autofire_selection:' + cause.selectionId, selection = await store.get(selectionKey);
  store.values[selectionKey] = Object.assign({}, selection, { ownerDomain: 'finance' });
  assert.equal((await Trace.read(readonly, product, at)).status, 'UNAVAILABLE');
  store.values[selectionKey] = selection;
  assert.equal((await Trace.read(readonly, product, at)).status, 'RECORDED');
  var unavailable = Object.create(readonly);
  unavailable.get = async function () { throw new Error('store unavailable'); };
  var failed = await Trace.read(unavailable, product, at);
  assert.equal(failed.status, 'UNAVAILABLE');
  assert.equal(failed.command, null);
  assert.equal(failed.decision, null);
};
