'use strict';
var assert = require('assert');
var fs = require('fs');
var path = require('path');
var child = require('child_process');
var root = path.join(__dirname, '..');
var out = path.join(root, 'assets', 'data', 'deep', 'domain-authoring-reconciliation-queue.json');
var before = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
var text = child.execFileSync(process.execPath, [path.join(__dirname, 'build-domain-authoring-reconciliation.js')], { cwd: root, encoding: 'utf8' });
var data = JSON.parse(text);
assert.strictEqual(data.schemaVersion, 'domain-authoring-reconciliation-queue/1.0');
assert.strictEqual(data.readOnlyAdmission, true);
assert.strictEqual(data.domains, 20);
assert.strictEqual(data.existingAuthoringQueueDomains, 20);
assert.strictEqual(data.openReconciliationTasks, 0);
assert.strictEqual(data.rows.filter(function (r) { return r.status === 'EXISTING_AUTHORING_QUEUE'; }).length, 20);
assert.strictEqual(data.rows.filter(function (r) { return r.domain === 'energy'; })[0].existingAuthoringTasks, 156);
assert.strictEqual(data.rows.filter(function (r) { return r.domain === 'science'; })[0].existingAuthoringTasks, 121);
assert.strictEqual(data.rows.filter(function (r) { return r.domain === 'medicine'; })[0].existingAuthoringTasks, 139);
assert.strictEqual(data.rows.filter(function (r) { return r.domain === 'finance'; })[0].existingAuthoringTasks, 140);
assert(data.tasks.every(function (t) { return t.status === 'OPEN' && t.type === 'domain-pipeline-admission'; }));
assert.strictEqual(data.tasks.length, 0);
assert(data.rows.every(function (r) { return r.existingAuthoringTasks > 0; }));
assert(!data.tasks.some(function (t) { return t.type === 'authoring-opportunity' || t.type === 'execution-input'; }));
assert.strictEqual(fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null, before, 'read-only test must not write the generated queue');
console.log('16/16 passed');
