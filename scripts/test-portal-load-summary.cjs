'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const acorn = require('acorn');
const walk = require('acorn-walk');
const source = fs.readFileSync(require.resolve('../assets/js/portal-ui.js'), 'utf8');
let projection;
walk.simple(acorn.parse(source, { ecmaVersion: 'latest' }), { FunctionDeclaration(node) {
  if (node.id.name === '_projectPortalLoad') projection = source.slice(node.start, node.end);
} });
assert(projection);
const elements = { reDesc: { textContent: 'Deep portal — loading from API.' }, reStats: { textContent: '0 active nodes' } };
let nodes = [{}, {}, {}, {}];
const context = vm.createContext({ document: { getElementById(id) { return elements[id] || null; } }, Engine: { getActivatedNodes() { return nodes; } } });
vm.runInContext(projection, context);
context._projectPortalLoad({ title: 'Rack Power Density' });
assert.equal(elements.reStats.textContent, '4 active nodes · 123 brain regions');
assert.equal(elements.reDesc.textContent, 'Portal data loaded.');
context._projectPortalLoad(null);
assert.equal(elements.reStats.textContent, 'UNOBSERVED · portal data unavailable');
assert.equal(elements.reDesc.textContent, 'Portal data unavailable.');
nodes = [{}, {}, {}];
context._projectPortalLoad({ description: 'High-voltage source description' });
assert.equal(elements.reStats.textContent, '3 active nodes · 123 brain regions');
assert.equal(elements.reDesc.textContent, 'High-voltage source description');
nodes = null;
context._projectPortalLoad({});
assert.equal(elements.reStats.textContent, 'UNOBSERVED · active-node count unavailable');
elements.reDesc.textContent = 'Authored registry description';
nodes = [];
context._projectPortalLoad({});
assert.equal(elements.reStats.textContent, '0 active nodes · 123 brain regions');
assert.equal(elements.reDesc.textContent, 'Authored registry description');
console.log('portal summary: loaded counts, unavailable count, failure and recovery passed');
