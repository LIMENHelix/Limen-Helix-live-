/**
 * print-pipeline.js — when operator accepts an artifact, prepare it for filing.
 *
 * Per active lane, generates the operator package:
 *   investment: thesis brief (markdown + JSON for Alpaca paper-trade scaffold)
 *   research: research note (markdown for OSF preregistration draft)
 *
 * Output written to: assets/printed/<lane>/<portalSlug>/<patternId>.{md, json}
 *
 * Retired patent/grant/SBA/franchise lanes have no renderer and cannot create
 * documents through this pipeline.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const PRINTED_DIR = path.join(ROOT, 'assets', 'printed');
const PORTALS_DIR = path.join(ROOT, 'assets', 'data', 'companies');

function _ensureDir(p) { fs.mkdirSync(p, { recursive: true }); }
function _loadPortal(slug) { try { return JSON.parse(fs.readFileSync(path.join(PORTALS_DIR, slug + '.json'), 'utf8')); } catch (e) { return null; } }
function _getArtifact(portal, lane, index) { const list = portal.engineOutputs && portal.engineOutputs[lane]; return list && list[index] || null; }
function _ts() { return new Date().toISOString().replace(/[:.]/g, '-'); }

function _investmentMarkdown(art) {
  const a = art.artifact || {};
  let md = '# Investment Thesis\n\n';
  md += '**Thesis statement**: ' + (a.thesisStatement || '—') + '\n\n';
  md += '## Header\n\n```\n' + (a.header || '') + '\n```\n\n';
  md += '## Variant View\n\n' + (a.variantView || '') + '\n\n';
  md += '## Catalysts\n\n```\n' + (a.catalystBlock || '') + '\n```\n\n';
  md += '## Valuation\n\n```\n' + (a.valuation || '') + '\n```\n\n';
  md += '## Position Sizing\n\n```\n' + (a.positionSizing || '') + '\n```\n\n';
  md += '## Risk · Falsifiability\n\n' + (a.risk || '') + '\n\n';
  md += '## Exit Conditions\n\n' + (a.exit || '') + '\n\n';
  if (art.side) md += '*Side: ' + art.side + ' · Horizon: ' + (art.horizon || '—') + '*\n\n';
  md += '---\n*Generated by LIMEN Helix bridge engine — pattern: ' + (art.patternId || 'unknown') + '*\n';
  return md;
}

function _researchMarkdown(art) {
  const a = art.artifact || {};
  let md = '# ' + (a.title || 'Research Note') + '\n\n';
  md += '## Hypothesis\n\n' + (a.hypothesis || '') + '\n\n';
  md += '## Methodology\n\n' + (a.methodology || '') + '\n\n';
  md += '## Preregistration plan\n\n' + (a.preregistration || '') + '\n\n';
  md += '## Falsifiability\n\n' + (a.falsifiability || '') + '\n\n';
  md += '## Expected outcome\n\n' + (a.expectedOutcome || '') + '\n\n';
  if (a.bridgeReference) md += '## Bridge reference\n\n`' + a.bridgeReference + '`\n\n';
  md += '---\n*Generated by LIMEN Helix bridge engine*\n';
  return md;
}

const LANE_RENDERERS = {
  investment: _investmentMarkdown,
  research: _researchMarkdown
};

// Main entry: print one artifact. Returns the file paths written.
function printArtifact({ portalSlug, lane, index, actionId }) {
  if (!Object.prototype.hasOwnProperty.call(LANE_RENDERERS, lane)) {
    return { ok: false, error: 'lane retired or unsupported: ' + lane + ' (active lanes: investment, research)' };
  }
  const portal = _loadPortal(portalSlug);
  if (!portal) return { ok: false, error: 'portal not found: ' + portalSlug };
  const art = _getArtifact(portal, lane, parseInt(index, 10));
  if (!art) return { ok: false, error: 'artifact not found: ' + portalSlug + '/' + lane + '/' + index };

  const slug = (art.patternId || ('idx' + index)).replace(/[^A-Za-z0-9_-]+/g, '_');
  const outDir = path.join(PRINTED_DIR, lane, portalSlug);
  _ensureDir(outDir);
  const ts = _ts();
  const stem = slug + '__' + ts;
  const renderer = LANE_RENDERERS[lane];
  if (!renderer) return { ok: false, error: 'no renderer for lane ' + lane };

  const md = renderer(art);
  const mdPath = path.join(outDir, stem + '.md');
  const jsonPath = path.join(outDir, stem + '.json');

  fs.writeFileSync(mdPath, md);
  fs.writeFileSync(jsonPath, JSON.stringify({
    portalSlug, lane, patternId: art.patternId, confidence: art.confidence,
    artifact: art.artifact, provenance: art.provenance,
    printedAt: new Date().toISOString(),
    actionId,
    status: 'READY_TO_FILE',
    externalSubmission: { investment: null, research: null }
  }, null, 2));

  return { ok: true, files: { md: path.relative(ROOT, mdPath), json: path.relative(ROOT, jsonPath) }, lane, portalSlug };
}

module.exports = { printArtifact };
